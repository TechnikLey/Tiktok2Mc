#!/usr/bin/env python3
"""Generate the code-derived developer reference documentation.

The reference is generated from the source of truth and must never be
edited by hand:

- ``docs/reference/error-codes.md``  ← ``core.error_codes`` registry
- ``docs/reference/config.md``       ← ``defaults/config.yaml`` + comments
- ``docs/reference/api.md``          ← FastAPI router (``core.api.routes``)

Usage:
    python tools/gen_reference.py            # write docs/reference/*.md
    python tools/gen_reference.py --check    # fail if the files are stale
"""

from __future__ import annotations

import argparse
import html
import re
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = PROJECT_ROOT / "src"
DEFAULT_OUT_DIR = PROJECT_ROOT / "docs" / "reference"

GENERATED_NOTE = (
    "<!-- Generated by tools/gen_reference.py — do not edit. "
    "Run `python build.py docs` after changing the source. -->"
)


def _ensure_src_on_path() -> None:
    """Make the ``core`` package importable when run as a plain script."""
    if str(SRC_DIR) not in sys.path:
        sys.path.insert(0, str(SRC_DIR))


def _clean(value: object) -> str:
    """Collapse whitespace so free text fits into a Markdown block."""
    return " ".join(str(value or "").split())


def _cell(value: object) -> str:
    """Render free text as a single, escaped Markdown table cell."""
    text = html.escape(_clean(value), quote=False)
    return text.replace("|", "\\|") or "—"


def _code(value: object) -> str:
    """Wrap a default value in inline code, guarding empty values."""
    text = _clean(value)
    return f"`{text}`" if text else "—"


# ---------------------------------------------------------------------------
# Error codes
# ---------------------------------------------------------------------------
def render_error_codes() -> str:
    """Render the complete error-code reference from the registry."""
    _ensure_src_on_path()
    from core.error_codes import Severity, list_all_codes

    codes = list_all_codes()
    by_subsystem: dict[str, list] = {}
    for code in codes:
        by_subsystem.setdefault(code.subsystem.value, []).append(code)

    lines = [
        "# Error code reference",
        "",
        GENERATED_NOTE,
        "",
        (
            f"All {len(codes)} registered error codes, grouped by subsystem. "
            "Codes are stable identifiers: never renumber existing codes, only "
            "append new ones."
        ),
        "",
        (
            "A running instance exposes the same data as JSON via "
            "`GET /api/v1/diagnostics/error-codes`."
        ),
        "",
        "| Subsystem | Codes |",
        "| --- | --- |",
    ]
    for subsystem in sorted(by_subsystem):
        lines.append(f"| `{subsystem}` | {len(by_subsystem[subsystem])} |")

    for subsystem in sorted(by_subsystem):
        lines.extend(["", f"## {subsystem}"])
        for code in by_subsystem[subsystem]:
            severity = code.severity
            severity_label = (
                severity.label() if isinstance(severity, Severity) else str(severity)
            )
            lines.extend(
                [
                    "",
                    f"### `{code.code}` — {severity_label}: {_clean(code.message)}",
                    "",
                ]
            )
            if _clean(code.description):
                lines.extend([_clean(code.description), ""])
            if _clean(code.recovery_hint):
                lines.append(f"- **Recovery:** {_clean(code.recovery_hint)}")
            if _clean(code.impact):
                lines.append(f"- **Impact:** {_clean(code.impact)}")
            if _clean(code.recovery_hint) or _clean(code.impact):
                lines.append("")

    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------
_KEY_LINE = re.compile(r"^( *)([A-Za-z0-9_]+):(?:\s*(.*?))?\s*$")


def _is_separator(text: str) -> bool:
    """Return True for ASCII banner lines such as ``---`` or ``===``."""
    return bool(text) and set(text) <= {"-", "="}


def parse_config_sections(config_path: Path) -> list[dict]:
    """Parse ``defaults/config.yaml`` into sections with their comments.

    Returns top-level sections in file order. Each section holds the keys
    below it (dotted paths, arbitrary nesting) with their leading comment
    block and raw default value. Banner separators reset the pending
    comment so decorative headers do not leak into descriptions.
    """
    sections: list[dict] = []
    current: dict | None = None
    stack: list[str] = []
    comments: list[str] = []

    for raw_line in config_path.read_text(encoding="utf-8").splitlines():
        line = raw_line.rstrip()
        stripped = line.strip()
        if not stripped:
            comments = []
            continue
        if stripped.startswith("#"):
            text = stripped.lstrip("#").strip()
            if _is_separator(text):
                comments = []
            elif text:
                comments.append(text)
            continue

        match = _KEY_LINE.match(line)
        if not match:
            # List items and other deeper content are documented separately.
            comments = []
            continue

        indent, key, value = match.group(1), match.group(2), (match.group(3) or "")
        value = value.strip()
        if len(indent) % 2 != 0:
            comments = []
            continue

        if not indent:
            current = {
                "key": key,
                "value": value,
                "description": " ".join(comments),
                "entries": [],
            }
            sections.append(current)
            stack = []
        else:
            level = len(indent) // 2
            stack = stack[: level - 1] + [key]
            if current is not None:
                current["entries"].append(
                    {
                        "path": ".".join([current["key"], *stack]),
                        "value": value,
                        "description": " ".join(comments),
                    }
                )
        comments = []

    return sections


def _render_config_nodes(nodes: dict[str, dict], depth: int = 0) -> list[str]:
    """Render nested config keys as an indented, readable bullet list."""
    lines: list[str] = []
    for name, node in nodes.items():
        label = f"**`{name}`**"
        description = _clean(node["description"])
        default = _clean(node["value"])
        text = f"{'  ' * depth}- {label}"
        if description:
            text += f" — {description.rstrip('.')}"
        if default:
            text += f" (default: {_code(default)})"
        lines.append(text)
        lines.extend(_render_config_nodes(node["children"], depth + 1))
    return lines


def _config_tree(entries: list[dict], section_key: str) -> dict[str, dict]:
    """Build a nested tree from the dotted key paths of one section."""
    tree: dict[str, dict] = {}
    for entry in entries:
        parts = entry["path"].split(".")
        if parts and parts[0] == section_key:
            parts = parts[1:]
        branch = tree
        node: dict | None = None
        for part in parts:
            node = branch.setdefault(
                part, {"value": "", "description": "", "children": {}}
            )
            branch = node["children"]
        if node is not None:
            if entry["value"]:
                node["value"] = entry["value"]
            if entry["description"]:
                node["description"] = entry["description"]
    return tree


def render_config(config_path: Path | None = None) -> str:
    """Render the configuration reference from ``defaults/config.yaml``."""
    path = config_path or (PROJECT_ROOT / "defaults" / "config.yaml")
    sections = parse_config_sections(path)

    lines = [
        "# Configuration reference",
        "",
        GENERATED_NOTE,
        "",
        (
            f"Generated from `{path.relative_to(PROJECT_ROOT).as_posix()}`. "
            "The comments in that file are the documentation — update them there "
            "and regenerate this page."
        ),
        "",
    ]
    for section in sections:
        lines.extend([f"## `{section['key']}`", ""])
        if _clean(section["description"]):
            lines.extend([_clean(section["description"]), ""])
        entries = section["entries"]
        if entries:
            lines.extend(_render_config_nodes(_config_tree(entries, section["key"])))
            lines.append("")
        else:
            lines.extend([f"**Default:** {_code(section['value'])}", ""])

    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# HTTP API
# ---------------------------------------------------------------------------
def _join_path(prefix: str, path: str) -> str:
    """Join a router prefix and a route path without doubling slashes."""
    parts = [part.strip("/") for part in (prefix, path) if part and part.strip("/")]
    return "/" + "/".join(parts)


def collect_api_routes() -> list[dict]:
    """Return every route registered on the ``/api/v1`` router."""
    _ensure_src_on_path()
    from core.api.routes import api_router

    routes: list[dict] = []

    def walk(router, prefix: str) -> None:
        for route in router.routes:
            include_context = getattr(route, "include_context", None)
            if include_context is not None and hasattr(route, "original_router"):
                walk(
                    route.original_router,
                    _join_path(prefix, include_context.prefix or ""),
                )
                continue

            path = getattr(route, "path", None)
            if path is None:
                continue

            methods = sorted(getattr(route, "methods", None) or [])
            if not methods:
                methods = ["WS" if "WebSocket" in type(route).__name__ else "—"]

            tags = list(getattr(route, "tags", None) or [])
            tag = tags[0] if tags else "Other"
            summary = _clean(getattr(route, "summary", None))
            if not summary:
                description = _clean(getattr(route, "description", None))
                summary = (
                    description.split(".")[0]
                    if description
                    else _clean(getattr(route, "name", "")).replace("_", " ").title()
                )

            for method in methods:
                routes.append(
                    {
                        "method": method,
                        "path": _join_path(prefix, path),
                        "summary": summary,
                        "tag": tag,
                    }
                )

    walk(api_router, "")
    routes.sort(key=lambda item: (item["tag"], item["path"], item["method"]))
    return routes


def render_api() -> str:
    """Render the REST/WebSocket API reference from the FastAPI router."""
    routes = collect_api_routes()
    tags: dict[str, list[dict]] = {}
    for route in routes:
        tags.setdefault(route["tag"], []).append(route)

    lines = [
        "# API reference",
        "",
        GENERATED_NOTE,
        "",
        (
            f"All {len(routes)} registered endpoints on the `/api/v1` router. "
            "Interactive OpenAPI docs are served by a running instance at "
            "`http://localhost:29185/docs`."
        ),
        "",
        "| Tag | Endpoints |",
        "| --- | --- |",
    ]
    for tag in sorted(tags):
        lines.append(f"| {_cell(tag)} | {len(tags[tag])} |")

    for tag in sorted(tags):
        lines.extend(["", f"## {_cell(tag)}", ""])
        lines.extend(["| Method | Path | Summary |", "| --- | --- | --- |"])
        for route in tags[tag]:
            lines.append(
                f"| {route['method']} | `{route['path']}` | {_cell(route['summary'])} |"
            )

    return "\n".join(lines).rstrip() + "\n"


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------
def build_reference() -> dict[str, str]:
    """Return the rendered reference pages keyed by file name."""
    return {
        "error-codes.md": render_error_codes(),
        "config.md": render_config(),
        "api.md": render_api(),
    }


def write_reference(out_dir: Path = DEFAULT_OUT_DIR) -> list[Path]:
    """Write the rendered reference pages and return their paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in build_reference().items():
        target = out_dir / name
        target.write_text(text, encoding="utf-8", newline="\n")
        written.append(target)
    return written


def check_reference(out_dir: Path = DEFAULT_OUT_DIR) -> list[Path]:
    """Return the paths whose generated content is missing or stale."""
    stale = []
    for name, text in build_reference().items():
        target = out_dir / name
        try:
            current = target.read_text(encoding="utf-8")
        except OSError:
            stale.append(target)
            continue
        if current != text:
            stale.append(target)
    return stale


def main(argv: list[str] | None = None) -> int:
    """Run the generator (``--check`` verifies instead of writing)."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit non-zero if docs/reference/ is out of date",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help=f"Output directory (default: {DEFAULT_OUT_DIR})",
    )
    args = parser.parse_args(argv)

    if args.check:
        stale = check_reference(args.out_dir)
        if stale:
            for path in stale:
                print(f"Out of date: {path}")
            print("Run: python build.py docs")
            return 1
        print("Reference documentation is up to date.")
        return 0

    for path in write_reference(args.out_dir):
        print(f"Wrote: {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
